#!/usr/bin/env python3
"""
export_model.py -- train the deployable model and export it to C for the ESP32.

Model: random forest on the ABC-normalised features (the variant that won the
leave-one-vehicle-out comparison), trained on ALL three vehicles
(ambiguous near-tag candidates excluded, as in ml_experiment.py).

Writes
  firmware/esp32/RoadSense_v4_ML/rs_ml_model.h   forest as flat arrays + rsml_predict()
  results/test_vectors.txt every candidate window + Python features/probabilities,
                           read by tests/esp32_ml_equivalence/test_ml.cpp to prove the C code matches
"""
import json, os
import numpy as np
import ml_experiment as M
import rs_features as rf
from sklearn.ensemble import RandomForestClassifier

N_TREES, DEPTH, LEAF, SEED = 40, 6, 2, 0
FS = "norm"


def cf(v, digits=9):
    """C float literal that always has a decimal point or exponent."""
    t = f"{float(v):.{digits}g}"
    if "." not in t and "e" not in t and "inf" not in t and "nan" not in t:
        t += ".0"
    return t + "f"


def f32_floor(t):
    """largest float32 <= t, so (float32 x <= stored) == (x <= t) exactly as sklearn decides."""
    f = np.float32(t)
    if float(f) > t:
        f = np.nextafter(f, np.float32(-np.inf))
    return f


def main():
    data = M.load()
    X = np.vstack([M.X_of(data[v]["cand"], FS)[~data[v]["amb"]] for v in M.VEH])
    y = np.concatenate([data[v]["y"][~data[v]["amb"]] for v in M.VEH])
    clf = RandomForestClassifier(n_estimators=N_TREES, max_depth=DEPTH, min_samples_leaf=LEAF,
                                 class_weight="balanced_subsample", random_state=SEED).fit(X, y)
    classes = list(clf.classes_)
    names = rf.FEATURES[FS]

    feat, thr, left, right, leafv, roots = [], [], [], [], [], []
    for est in clf.estimators_:
        t = est.tree_
        base = len(feat); roots.append(base)
        for i in range(t.node_count):
            if t.children_left[i] == -1:
                v = t.value[i][0]; v = v / v.sum()
                feat.append(-1); thr.append(np.float32(0)); left.append(len(leafv)); right.append(-1)
                leafv.append([float(x) for x in v])
            else:
                feat.append(int(t.feature[i])); thr.append(f32_floor(t.threshold[i]))
                left.append(base + int(t.children_left[i])); right.append(base + int(t.children_right[i]))
    n_nodes, n_leaves = len(feat), len(leafv)
    flash = n_nodes * (1 + 4 + 2 + 2) + n_leaves * 3 * 4 + len(roots) * 2

    os.makedirs("results", exist_ok=True)
    L = []
    L.append("// rs_ml_model.h -- GENERATED by export_model.py, do not edit by hand.")
    L.append(f"// Random forest: {N_TREES} trees, max depth {DEPTH}, {n_nodes} nodes, {n_leaves} leaves,")
    L.append(f"// ~{flash/1024:.1f} KB of flash (const arrays). Trained on {len(y)} event windows from 3 vehicles.")
    L.append(f"// Features: ABC-normalised set ({len(names)}), order below. Classes: " + ", ".join(classes))
    L.append("#pragma once\n#include <stdint.h>\n")
    L.append(f"#define RSML_NFEAT {len(names)}\n#define RSML_NTREES {N_TREES}\n#define RSML_NCLASS {len(classes)}")
    for k, c in enumerate(classes):
        L.append(f"#define RSML_CLASS_{c} {k}")
    L.append("static const char* const RSML_FEATURE_NAMES[RSML_NFEAT] = {" + ", ".join(f'"{n}"' for n in names) + "};")
    L.append("static const char* const RSML_CLASS_NAMES[RSML_NCLASS] = {" + ", ".join(f'"{c}"' for c in classes) + "};")

    def arr(ctype, name, vals, per=16, fmt=str):
        L.append(f"static const {ctype} {name}[{len(vals)}] = {{")
        for i in range(0, len(vals), per):
            L.append("  " + ", ".join(fmt(v) for v in vals[i:i + per]) + ",")
        L.append("};")
    arr("int8_t", "RSML_FEAT", feat)
    arr("float", "RSML_THR", thr, 8, lambda v: cf(v))
    arr("int16_t", "RSML_LEFT", left)
    arr("int16_t", "RSML_RIGHT", right)
    arr("uint16_t", "RSML_ROOT", roots)
    arr("float", "RSML_LEAF", [x for v in leafv for x in v], 9, lambda v: cf(v, 7))
    L.append("""
// Averaged class probabilities (same as sklearn predict_proba). x: RSML_NFEAT features.
static inline void rsml_predict(const float* x, float* proba) {
  for (int c = 0; c < RSML_NCLASS; c++) proba[c] = 0;
  for (int t = 0; t < RSML_NTREES; t++) {
    int i = RSML_ROOT[t];
    while (RSML_FEAT[i] >= 0) i = (x[RSML_FEAT[i]] <= RSML_THR[i]) ? RSML_LEFT[i] : RSML_RIGHT[i];
    const float* v = &RSML_LEAF[RSML_LEFT[i] * RSML_NCLASS];
    for (int c = 0; c < RSML_NCLASS; c++) proba[c] += v[c];
  }
  for (int c = 0; c < RSML_NCLASS; c++) proba[c] /= RSML_NTREES;
}""")
    hdr = "\n".join(L) + "\n"
    for out in ("../firmware/esp32/RoadSense_v4_ML/rs_ml_model.h", "../firmware/stm32/Inc/rs_ml_model.h"):
        open(out, "w").write(hdr)

    # test vectors: every candidate of every vehicle (incl. ambiguous ones)
    with open("results/test_vectors.txt", "w") as f:
        n_ev = 0
        for v in M.VEH:
            for e in data[v]["cand"]:
                w, c = e["win"], e["cal"]
                f.write(f"EV {v} {e['t']} {len(w['ms'])} {w['t0']}\n")
                f.write("CAL " + " ".join(f"{c[k]:.9g}" for k in ("mu_j", "sig_j", "mu_h", "sig_h", "mu_r", "sig_r", "m1s")) + "\n")
                f.write(f"RULE {e['heaveDurMs']} {e['nHits']} {e['hitSpanMs']} {e['firstSign']}\n")
                for k in ("ms", "j", "h", "av", "ah"):
                    f.write(k.upper() + " " + " ".join(str(x) if k == "ms" else f"{x:.9g}" for x in w[k]) + "\n")
                f.write("PYF " + " ".join(f"{e['feat'][k]:.9g}" for k in names) + "\n")
                p = clf.predict_proba(np.array([[e["feat"][k] for k in names]]))[0]
                f.write("PYP " + " ".join(f"{x:.9g}" for x in p) + "\n")
                n_ev += 1
    print(f"forest: {N_TREES} trees, {n_nodes} nodes, {n_leaves} leaves, ~{flash/1024:.1f} KB flash; classes {classes}")
    print(f"wrote rs_ml_model.h (ESP32 + STM32) and results/test_vectors.txt ({n_ev} windows)")


if __name__ == "__main__":
    main()
